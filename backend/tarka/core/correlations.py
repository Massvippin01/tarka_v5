"""Explainable Evidence Correlation Engine for TARKA.

Deterministic Rules:
1. RULE_TXN_REF_EXACT: Exact transaction reference (RRN/Txn ID) match across sources.
2. RULE_PHONE_EXACT: Exact normalized phone number (MSISDN) match between chat/CDR/records.
3. RULE_VPA_EXACT: Exact UPI VPA match between chat payment requests and bank statements.
4. RULE_AMOUNT_WINDOW: Identical amount observed within configurable time window.
5. RULE_PAYMENT_FLOW_CAUSAL: Chat payment request preceding corresponding bank debit transaction.
6. RULE_CALL_PROXIMITY: Voice call involving related phone number near the timestamp of a payment or transaction.
7. RULE_MEDIA_TXN_MISMATCH: Screenshot/claim value conflicting with official transaction record (Contradiction).
8. RULE_MEDIA_TXN_MATCH: Screenshot/claim corroborating official transaction record.
9. RULE_EVIDENCE_GAP_MISSING_TXN: Unverified payment claim with no corresponding bank transaction (Evidence Gap).

Hard Forensic Requirements:
- No black-box scores.
- Visible, auditable, deterministic criteria.
- Never claim fraud certainty, guilt, or legal proof.
"""

from __future__ import annotations

import datetime
from enum import Enum
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field

from tarka.core.canonical_fact import (
    CanonicalFact,
    CanonicalFactKind,
    get_verified_utc_epoch,
)


class CorrelationStatus(str, Enum):
    """Forensic status of an evidence correlation."""
    SUPPORTED = "SUPPORTED"
    PROPOSED = "PROPOSED"
    REJECTED = "REJECTED"
    REVIEW_REQUIRED = "REVIEW_REQUIRED"


class EventCorrelation(BaseModel):
    """An explainable evidence relationship generated by visible deterministic rules."""
    correlation_id: str = Field(description="Unique deterministic identifier for this correlation")
    rule_id: str = Field(description="Deterministic rule identifier (e.g. RULE_TXN_REF_EXACT)")
    rule_name: str = Field(description="Human-readable rule title")
    rule_version: str = Field(default="1.0.0", description="Rule implementation version")
    evidence_inputs: List[str] = Field(description="List of linked Evidence DNA IDs")
    artifact_inputs: List[str] = Field(description="List of source Artifact IDs")
    time_window: Optional[Dict[str, Any]] = Field(
        default=None,
        description="Temporal interval evaluated (delta_seconds, max_allowed_seconds, timestamps)",
    )
    explanation_text: str = Field(description="Objective, non-accusatory forensic explanation")
    status: CorrelationStatus = Field(default=CorrelationStatus.SUPPORTED, description="Correlation outcome status")
    is_contradiction: bool = Field(default=False, description="True if facts are mutually incompatible")
    is_evidence_gap: bool = Field(default=False, description="True if expected corroborating evidence is missing")
    rejection_reason: Optional[str] = Field(default=None, description="Technical reason if rejected")
    examiner_review_state: str = Field(default="UNREVIEWED", description="Examiner review status: UNREVIEWED, CONFIRMED, or REJECTED")
    examiner_notes: Optional[str] = Field(default=None, description="Notes entered by reviewing investigator")


class EvidenceGap(BaseModel):
    """An identified gap where a claim or event lacks expected corroborating telemetry."""
    gap_id: str = Field(description="Deterministic gap identifier")
    rule_id: str = Field(description="Rule identifying the gap")
    claiming_fact_id: str = Field(description="Fact asserting the uncorroborated event")
    claiming_evidence_id: str = Field(description="Evidence DNA ID making the claim")
    artifact_id: str = Field(description="Parent artifact ID")
    expected_evidence_type: str = Field(description="Expected type (e.g. Bank Debit Transaction, Telco CDR)")
    search_parameters: Dict[str, Any] = Field(description="Parameters searched without matching record")
    explanation: str = Field(description="Objective explanation of the missing corroboration")


class CorrelationEngine:
    """Executes deterministic correlation rules across canonical facts."""

    def __init__(
        self,
        amount_time_window_seconds: float = 1800.0,  # 30 minutes
        payment_flow_max_delta_seconds: float = 3600.0,  # 1 hour
        call_proximity_max_delta_seconds: float = 1800.0,  # 30 minutes
    ) -> None:
        self.amount_window_sec = amount_time_window_seconds
        self.payment_flow_max_sec = payment_flow_max_delta_seconds
        self.call_proximity_max_sec = call_proximity_max_delta_seconds

    def correlate_case(
        self,
        facts: List[CanonicalFact],
    ) -> Tuple[List[EventCorrelation], List[EvidenceGap]]:
        """Runs all deterministic correlation rules across the case facts."""
        correlations: List[EventCorrelation] = []
        gaps: List[EvidenceGap] = []
        corr_seq = 1

        # Separate facts by kinds for targeted correlation
        chat_facts = [f for f in facts if f.kind in [CanonicalFactKind.CHAT_MESSAGE, CanonicalFactKind.PAYMENT_REQUEST]]
        bank_facts = [f for f in facts if f.kind == CanonicalFactKind.BANK_TRANSACTION]
        cdr_facts = [f for f in facts if f.kind == CanonicalFactKind.CDR_CALL]
        media_facts = [f for f in facts if f.kind == CanonicalFactKind.MEDIA_METADATA]

        # 1. Exact Transaction Reference Match (RULE_TXN_REF_EXACT)
        # Compares any fact with a normalized RRN/txn_ref against bank transactions
        for f1 in facts:
            rrn1 = f1.identifiers.get("rrn")
            if not rrn1:
                continue
            for f2 in facts:
                if f1.fact_id >= f2.fact_id:
                    continue  # Avoid duplicate pairs
                if f1.artifact_id == f2.artifact_id:
                    continue  # Cross-artifact correlation
                rrn2 = f2.identifiers.get("rrn")

                if rrn2 and rrn1 == rrn2:
                    dt = abs(f1.time_provenance.utc_epoch - f2.time_provenance.utc_epoch)
                    correlations.append(
                        EventCorrelation(
                            correlation_id=f"CORR-{corr_seq:04d}",
                            rule_id="RULE_TXN_REF_EXACT",
                            rule_name="Exact Transaction Reference Match",
                            evidence_inputs=[f1.evidence_id, f2.evidence_id],
                            artifact_inputs=list(set([f1.artifact_id, f2.artifact_id])),
                            time_window={"delta_seconds": dt, "f1_utc": f1.time_provenance.utc_iso, "f2_utc": f2.time_provenance.utc_iso},
                            explanation_text=(
                                f"Exact transaction reference match (RRN: {rrn1}) connects {f1.kind.value} "
                                f"({f1.source_filename}) with {f2.kind.value} ({f2.source_filename})."
                            ),
                            status=CorrelationStatus.SUPPORTED,
                        )
                    )
                    corr_seq += 1

        # 2. Exact UPI VPA Match (RULE_VPA_EXACT)
        for chat in chat_facts:
            vpa1 = chat.identifiers.get("vpa")
            if not vpa1:
                continue
            for bnk in bank_facts:
                vpa2 = bnk.identifiers.get("vpa")
                if vpa2 and vpa1.lower() == vpa2.lower():
                    t1 = get_verified_utc_epoch(chat)
                    t2 = get_verified_utc_epoch(bnk)
                    dt = abs(t1 - t2) if (t1 is not None and t2 is not None) else None
                    correlations.append(
                        EventCorrelation(
                            correlation_id=f"CORR-{corr_seq:04d}",
                            rule_id="RULE_VPA_EXACT",
                            rule_name="Exact UPI VPA Match",
                            evidence_inputs=[chat.evidence_id, bnk.evidence_id],
                            artifact_inputs=list(set([chat.artifact_id, bnk.artifact_id])),
                            time_window={"delta_seconds": dt},
                            explanation_text=(
                                f"Identical UPI Virtual Payment Address ({vpa1}) requested in chat "
                                f"matches recipient payee VPA in bank debit record."
                            ),
                            status=CorrelationStatus.SUPPORTED,
                        )
                    )
                    corr_seq += 1

        # 3. Exact Phone Number Match between CDR and Chat/Bank (RULE_PHONE_EXACT)
        for cdr in cdr_facts:
            cdr_phone = cdr.identifiers.get("msisdn") or cdr.primary_entity
            if not cdr_phone:
                continue
            for other in (chat_facts + bank_facts):
                other_phone = other.identifiers.get("msisdn") or other.primary_entity
                if other_phone and cdr_phone == other_phone:
                    t_cdr = get_verified_utc_epoch(cdr)
                    t_other = get_verified_utc_epoch(other)
                    dt = abs(t_cdr - t_other) if (t_cdr is not None and t_other is not None) else None
                    time_win = {"delta_seconds": dt} if dt is not None else {"delta_seconds": None, "note": "Timestamp not recorded on one or more records"}
                    correlations.append(
                        EventCorrelation(
                            correlation_id=f"CORR-{corr_seq:04d}",
                            rule_id="RULE_PHONE_EXACT",
                            rule_name="Exact Phone Number Cross-Source Link",
                            evidence_inputs=[cdr.evidence_id, other.evidence_id],
                            artifact_inputs=list(set([cdr.artifact_id, other.artifact_id])),
                            time_window=time_win,
                            explanation_text=(
                                f"Normalized phone number ({cdr_phone}) connects cellular CDR call record "
                                f"with {other.kind.value} in {other.source_filename}."
                            ),
                            status=CorrelationStatus.SUPPORTED,
                        )
                    )
                    corr_seq += 1

        # 4. Chat Payment Request Preceding Bank Transaction (RULE_PAYMENT_FLOW_CAUSAL)
        for chat in chat_facts:
            if chat.kind != CanonicalFactKind.PAYMENT_REQUEST and chat.amount is None:
                continue
            for bnk in bank_facts:
                t_chat = get_verified_utc_epoch(chat)
                t_bnk = get_verified_utc_epoch(bnk)
                if t_chat is None or t_bnk is None:
                    continue
                delta = t_bnk - t_chat
                # Request must happen before or up to 10 seconds after bank transaction
                if 0 <= delta <= self.payment_flow_max_sec:
                    # Check if amounts match or VPAs match
                    same_amt = (chat.amount is not None and bnk.amount is not None and abs(chat.amount - bnk.amount) < 0.01)
                    same_vpa = (
                        chat.identifiers.get("vpa")
                        and bnk.identifiers.get("vpa")
                        and chat.identifiers.get("vpa").lower() == bnk.identifiers.get("vpa").lower()
                    )
                    if same_amt or same_vpa:
                        correlations.append(
                            EventCorrelation(
                                correlation_id=f"CORR-{corr_seq:04d}",
                                rule_id="RULE_PAYMENT_FLOW_CAUSAL",
                                rule_name="Causal Chat Payment Request Flow",
                                evidence_inputs=[chat.evidence_id, bnk.evidence_id],
                                artifact_inputs=list(set([chat.artifact_id, bnk.artifact_id])),
                                time_window={"delta_seconds": delta, "max_allowed_seconds": self.payment_flow_max_sec},
                                explanation_text=(
                                    f"Payment request in chat occurred {delta:.0f} seconds prior to corresponding "
                                    f"bank debit transaction (Amount: ₹{bnk.amount:,.2f} if applicable), consistent with requested transfer."
                                ),
                                status=CorrelationStatus.SUPPORTED,
                            )
                        )
                        corr_seq += 1

        # 5. Matching Amount within Time Window (RULE_AMOUNT_WINDOW)
        for chat in chat_facts:
            if chat.amount is None:
                continue
            for bnk in bank_facts:
                if bnk.amount is None:
                    continue
                if abs(chat.amount - bnk.amount) < 0.01:
                    t_chat = get_verified_utc_epoch(chat)
                    t_bnk = get_verified_utc_epoch(bnk)
                    if t_chat is None or t_bnk is None:
                        continue
                    delta = abs(t_chat - t_bnk)
                    if delta <= self.amount_window_sec:
                        correlations.append(
                            EventCorrelation(
                                correlation_id=f"CORR-{corr_seq:04d}",
                                rule_id="RULE_AMOUNT_WINDOW",
                                rule_name="Identical Amount in Temporal Window",
                                evidence_inputs=[chat.evidence_id, bnk.evidence_id],
                                artifact_inputs=list(set([chat.artifact_id, bnk.artifact_id])),
                                time_window={"delta_seconds": delta, "window_seconds": self.amount_window_sec},
                                explanation_text=(
                                    f"Identical financial amount (₹{chat.amount:,.2f}) observed within {delta:.0f} seconds "
                                    f"across chat request and bank transaction."
                                ),
                                status=CorrelationStatus.SUPPORTED,
                            )
                        )
                        corr_seq += 1

        # 6. Voice Call Near Relevant Event (RULE_CALL_PROXIMITY)
        for cdr in cdr_facts:
            for ev in (chat_facts + bank_facts):
                t_cdr = get_verified_utc_epoch(cdr)
                t_ev = get_verified_utc_epoch(ev)
                if t_cdr is None or t_ev is None:
                    continue
                delta = abs(t_cdr - t_ev)
                if delta <= self.call_proximity_max_sec:
                    # Check shared phone or common party
                    cdr_phone = cdr.identifiers.get("msisdn") or cdr.primary_entity
                    ev_phone = ev.identifiers.get("msisdn") or ev.primary_entity
                    if cdr_phone and ev_phone and cdr_phone == ev_phone:
                        correlations.append(
                            EventCorrelation(
                                correlation_id=f"CORR-{corr_seq:04d}",
                                rule_id="RULE_CALL_PROXIMITY",
                                rule_name="Cellular Voice Call Near Communication/Transaction",
                                evidence_inputs=[cdr.evidence_id, ev.evidence_id],
                                artifact_inputs=list(set([cdr.artifact_id, ev.artifact_id])),
                                time_window={"delta_seconds": delta, "max_allowed_seconds": self.call_proximity_max_sec},
                                explanation_text=(
                                    f"Cellular call involving {cdr_phone} occurred {delta:.0f} seconds near "
                                    f"{ev.kind.value} ({ev.source_filename})."
                                ),
                                status=CorrelationStatus.SUPPORTED,
                            )
                        )
                        corr_seq += 1

        # 7. Screenshot / Media Claim vs Transaction Match & Conflict (Contradiction)
        for media in media_facts:
            claimed_rrn = media.identifiers.get("rrn")
            claimed_amt = media.amount
            claimed_vpa = media.identifiers.get("vpa")

            matched_bank_txns = []
            for bnk in bank_facts:
                bnk_rrn = bnk.identifiers.get("rrn")
                if claimed_rrn and bnk_rrn and claimed_rrn == bnk_rrn:
                    matched_bank_txns.append(bnk)

            if matched_bank_txns:
                for bnk in matched_bank_txns:
                    # Check if amount conflicts
                    if claimed_amt is not None and bnk.amount is not None:
                        amt_delta = abs(claimed_amt - bnk.amount)
                        if amt_delta > 0.01:
                            # CONTRADICTION!
                            correlations.append(
                                EventCorrelation(
                                    correlation_id=f"CORR-{corr_seq:04d}",
                                    rule_id="RULE_MEDIA_TXN_MISMATCH",
                                    rule_name="Claimed Media Amount Conflict",
                                    evidence_inputs=[media.evidence_id, bnk.evidence_id],
                                    artifact_inputs=list(set([media.artifact_id, bnk.artifact_id])),
                                    time_window={"media_utc": media.time_provenance.utc_iso, "bank_utc": bnk.time_provenance.utc_iso},
                                    explanation_text=(
                                        f"Factual contradiction: Screenshot/claim indicates amount ₹{claimed_amt:,.2f}, "
                                        f"whereas bank transaction RRN {claimed_rrn} records ₹{bnk.amount:,.2f}. "
                                        f"Discrepancy delta = ₹{amt_delta:,.2f}."
                                    ),
                                    status=CorrelationStatus.REJECTED,
                                    is_contradiction=True,
                                    rejection_reason=f"Financial amount mismatch (Claim ₹{claimed_amt:,.2f} != Bank ₹{bnk.amount:,.2f})",
                                    examiner_review_state="REVIEW_REQUIRED",
                                )
                            )
                            corr_seq += 1
                        else:
                            # Match
                            correlations.append(
                                EventCorrelation(
                                    correlation_id=f"CORR-{corr_seq:04d}",
                                    rule_id="RULE_MEDIA_TXN_MATCH",
                                    rule_name="Corroborated Media Claim and Bank Record",
                                    evidence_inputs=[media.evidence_id, bnk.evidence_id],
                                    artifact_inputs=list(set([media.artifact_id, bnk.artifact_id])),
                                    explanation_text=(
                                        f"Screenshot claim amount (₹{claimed_amt:,.2f}) and RRN ({claimed_rrn}) "
                                        f"are fully corroborated by bank transaction record."
                                    ),
                                    status=CorrelationStatus.SUPPORTED,
                                    is_contradiction=False,
                                )
                            )
                            corr_seq += 1
            else:
                # 8. Unverified Claim with No Bank Record (Evidence Gap)
                if claimed_rrn or (claimed_amt is not None and claimed_vpa):
                    gap_id = f"GAP-{len(gaps) + 1:03d}"
                    gap = EvidenceGap(
                        gap_id=gap_id,
                        rule_id="RULE_EVIDENCE_GAP_MISSING_TXN",
                        claiming_fact_id=media.fact_id,
                        claiming_evidence_id=media.evidence_id,
                        artifact_id=media.artifact_id,
                        expected_evidence_type="Bank Transaction Record (NPCI/Core Banking)",
                        search_parameters={
                            "claimed_rrn": claimed_rrn,
                            "claimed_amount": claimed_amt,
                            "claimed_payee_vpa": claimed_vpa,
                        },
                        explanation=(
                            f"Evidence gap: Media claim asserts payment of {f'₹{claimed_amt:,.2f}' if claimed_amt is not None else 'unspecified amount'} "
                            f"(RRN: {claimed_rrn or 'None'}) to {claimed_vpa or 'None'}, but no matching "
                            f"transaction entry exists in the supplied bank statements."
                        ),
                    )
                    gaps.append(gap)
                    correlations.append(
                        EventCorrelation(
                            correlation_id=f"CORR-{corr_seq:04d}",
                            rule_id="RULE_EVIDENCE_GAP_MISSING_TXN",
                            rule_name="Uncorroborated Payment Claim",
                            evidence_inputs=[media.evidence_id],
                            artifact_inputs=[media.artifact_id],
                            explanation_text=gap.explanation,
                            status=CorrelationStatus.PROPOSED,
                            is_evidence_gap=True,
                            examiner_review_state="REVIEW_REQUIRED",
                        )
                    )
                    corr_seq += 1

        return correlations, gaps
